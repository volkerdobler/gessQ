'use strict';

/**
 * Regenerate `src/data/language.ts` from the TextMate grammar so the
 * completion provider has a single, non-scraped source of gessQ keywords.
 *
 *   node tools/gen-language.js
 *
 * The grammar (`language/gessq.tmLanguage.json`) stays the hand-authored
 * source of truth; this script only mirrors its keyword alternations into a
 * typed module.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const grammar = JSON.parse(
	fs.readFileSync(
		path.join(ROOT, 'language', 'gessq.tmLanguage.json'),
		'utf8',
	),
);

/** Split the first `( … | … )` alternation in `source` into lowercase words. */
function alternation(source, afterMarker) {
	let s = source;
	if (afterMarker) {
		const at = s.indexOf(afterMarker);
		if (at < 0) return [];
		s = s.slice(at + afterMarker.length);
	}
	const open = s.indexOf('(');
	if (open < 0) return [];
	let depth = 0;
	let end = -1;
	for (let i = open; i < s.length; i++) {
		if (s[i] === '(') depth++;
		else if (s[i] === ')') {
			depth--;
			if (depth === 0) {
				end = i;
				break;
			}
		}
	}
	if (end < 0) return [];
	return s
		.slice(open + 1, end)
		.split('|')
		.map((w) => w.trim().replace(/^\?i:/, ''))
		.filter((w) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(w))
		.map((w) => w.toLowerCase());
}

const patterns = grammar.patterns || [];
const byName = (name) => patterns.find((p) => p.name === name) || {};

const coreKeywords = alternation(patterns[0].match || '', '\\b');
const commands = alternation(
	byName('support.class.gessQ').match || '',
	'(?<!\\.)',
);
const parameters = alternation(
	byName('support.constant.gessQ').match || '',
	'(?i:',
);

const directives = [
	'@insert',
	'#define',
	'#domacro',
	'#ifdef',
	'#ifndef',
	'#include',
	'#includeifexists',
	'#macro',
	'#endmacro',
	'#else',
	'#endif',
];

const uniqSorted = (a) => [...new Set(a)].sort();

const list = (name, arr, kind) =>
	`/** ${name} */\nexport const ${name}: readonly string[] = ${JSON.stringify(
		uniqSorted(arr),
		null,
		1,
	).replace(/\n /g, '\n\t')};\n`;

const banner =
	'// AUTO-GENERATED by tools/gen-language.js from language/gessq.tmLanguage.json.\n' +
	'// Do not edit by hand; run `npm run gen:language` after changing the grammar.\n\n' +
	"'use strict';\n\n";

const body =
	banner +
	list('CORE_KEYWORDS', coreKeywords) +
	'\n' +
	list('DIRECTIVES', directives) +
	'\n' +
	list('COMMANDS', commands) +
	'\n' +
	list('PARAMETERS', parameters) +
	'\n' +
	'/** Every completable keyword, de-duplicated and sorted. */\n' +
	'export const ALL_KEYWORDS: readonly string[] = [\n' +
	'\t...CORE_KEYWORDS,\n\t...DIRECTIVES,\n\t...COMMANDS,\n\t...PARAMETERS,\n' +
	'].filter((v, i, a) => a.indexOf(v) === i).sort();\n';

fs.writeFileSync(path.join(ROOT, 'src', 'data', 'language.ts'), body);
console.log(
	`language.ts: ${coreKeywords.length} core, ${directives.length} directives, ` +
		`${commands.length} commands, ${parameters.length} parameters`,
);
